# 1. Integer (int)
age = 22
print("Integer:", age)
print("Type:", type(age))


# 2. Float (float)
price = 99.50
print("\nFloat:", price)
print("Type:", type(price))


# 3. Complex (complex)
number = 5 + 3j
print("\nComplex:", number)
print("Type:", type(number))


# 4. Boolean (bool)
is_student = True
print("\nBoolean:", is_student)
print("Type:", type(is_student))


# 5. String (str)
name = "Roshan"
print("\nString:", name)
print("Type:", type(name))


# 6. List (list)
marks = [80, 85, 90, 95]
print("\nList:", marks)
print("Type:", type(marks))


# 7. Tuple (tuple)
numbers = (10, 20, 30, 40)
print("\nTuple:", numbers)
print("Type:", type(numbers))


# 8. Set (set)
unique_numbers = {10, 20, 30, 20}
print("\nSet:", unique_numbers)
print("Type:", type(unique_numbers))


# 9. Dictionary (dict)
student = {
    "id": 101,
    "name": "Roshan",
    "age": 22
}
print("\nDictionary:", student)
print("Type:", type(student))


# 10. Range (range)
number_range = range(1, 6)
print("\nRange:", number_range)
print("Type:", type(number_range))


# 11. None (NoneType)
result = None
print("\nNone:", result)
print("Type:", type(result))


# 12. Frozenset (frozenset)
fixed_set = frozenset([10, 20, 30])
print("\nFrozenset:", fixed_set)
print("Type:", type(fixed_set))